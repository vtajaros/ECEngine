import { describe, it, expect } from 'vitest'
import {
  detectSubjectFromCards,
  scoreCardText,
  extractCardText,
  GenericCardInput,
} from './subjectClassifier'

describe('subjectClassifier', () => {
  describe('scoreCardText', () => {
    it('correctly scores math calculus questions with LaTeX formulas', () => {
      const text = 'Evaluate the integral \\int_{0}^{1} x^2 \\sqrt{1 - x^2} dx'
      const res = scoreCardText(text)
      expect(res.winner).toBe('MATH')
      expect(res.scores.MATH).toBeGreaterThan(10)
    })

    it('correctly scores math word problems even when physics terms (velocity, acceleration) are used', () => {
      const text = 'A particle moves along a curve where s(t) = 3t^3 - 2t. Find the rate of change and the acceleration of the particle at t = 2 by computing the second derivative d^2s/dt^2.'
      const res = scoreCardText(text)
      expect(res.winner).toBe('MATH')
      expect(res.scores.MATH).toBeGreaterThan(res.scores.GEAS)
    })

    it('correctly scores GEAS Engineering Economics questions', () => {
      const text = 'A machine has a first cost of P100,000 and a salvage value of P10,000 at the end of its 8-year life. Using straight line depreciation, calculate the book value after 3 years.'
      const res = scoreCardText(text)
      expect(res.winner).toBe('GEAS')
      expect(res.scores.GEAS).toBeGreaterThan(10)
    })

    it('correctly scores GEAS Materials Science / Chemistry / Laws questions', () => {
      const text = 'Under RA 9292, the Professional Electronics Engineer (PECE) is authorized to sign and seal electronics engineering documents.'
      const res = scoreCardText(text)
      expect(res.winner).toBe('GEAS')
    })

    it('correctly scores ELECS Transistor and Op-Amp questions', () => {
      const text = 'For a silicon BJT in common emitter configuration, find the Q-point and collector current given Vcc = 12V and base current division.'
      const res = scoreCardText(text)
      expect(res.winner).toBe('ELECS')
    })

    it('correctly scores EST Communications and Transmission lines questions', () => {
      const text = 'Calculate the characteristic impedance and standing wave ratio (VSWR) of a lossless transmission line given the reflection coefficient is 0.2.'
      const res = scoreCardText(text)
      expect(res.winner).toBe('EST')
    })
  })

  describe('detectSubjectFromCards - Minority Filtering & Deck Aggregation', () => {
    it('classifies a Math deck as Mathematics even if minority cards mention physics context', () => {
      const mathCards: GenericCardInput[] = [
        {
          type: 'mcq',
          data: {
            question: 'Find the derivative of f(x) = \\frac{x^2 + 1}{x - 1}',
            choices: ['\\frac{x^2-2x-1}{(x-1)^2}', '2x', '\\frac{2x}{x-1}', 'None'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'Evaluate the limit as x approaches 0 of \\frac{\\sin(3x)}{x}',
            choices: ['3', '1', '0', '\\infty'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'Solve the first-order differential equation dy/dx + 2y = 4',
            choices: ['y = 2 + Ce^{-2x}', 'y = Ce^{2x}', 'y = 4x + C', 'y = 2'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'Find the area bounded by the parabola y = x^2 and the line y = 4',
            choices: ['32/3', '16/3', '8/3', '64/3'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'Find the eigenvalues of the matrix \\begin{pmatrix} 2 & 1 \\\\ 1 & 2 \\end{pmatrix}',
            choices: ['1 and 3', '2 and 2', '0 and 4', '-1 and 3'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'Calculate the probability of drawing 2 aces from a standard deck of 52 cards without replacement',
            choices: ['1/221', '1/13', '1/26', '1/169'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'Find the volume generated by revolving the region bounded by y = \\sqrt{x} about the x-axis from x=0 to x=4',
            choices: ['8\\pi', '16\\pi', '4\\pi', '2\\pi'],
          },
        },
        // Word problem with physics wording (velocity/pressure)
        {
          type: 'mcq',
          data: {
            question: 'Water is pumped into an inverted cone at 2 m^3/min. Find the rate of change of depth when depth is 3m.',
            choices: ['0.07 m/min', '0.14 m/min', '0.21 m/min', '0.5 m/min'],
          },
        },
      ]

      const result = detectSubjectFromCards(mathCards)
      expect(result.subject).toBe('Mathematics')
      expect(result.code).toBe('MATH')
      expect(result.cardVotes.MATH).toBeGreaterThanOrEqual(6)
      expect(result.confidence).toBeGreaterThan(0.7)
    })

    it('classifies a GEAS deck properly', () => {
      const geasCards: GenericCardInput[] = [
        {
          type: 'mcq',
          data: {
            question: 'Calculate the capitalized cost of a project with initial cost P5,000,000 and annual maintenance P200,000 at 10% interest rate.',
            choices: ['P7,000,000', 'P6,500,000', 'P8,000,000', 'P5,200,000'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'What is the crystal structure of alpha-iron at room temperature?',
            choices: ['Body-Centered Cubic (BCC)', 'Face-Centered Cubic (FCC)', 'HCP', 'Amorphous'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'A Carnot engine operates between 600 K and 300 K. What is the maximum theoretical efficiency?',
            choices: ['50%', '60%', '40%', '75%'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'According to RA 9292, what board exam rating is required to pass the ECE licensure examination?',
            choices: ['70% overall with no grade below 50%', '75% overall', '60%', '80%'],
          },
        },
      ]

      const result = detectSubjectFromCards(geasCards)
      expect(result.subject).toBe('General Engineering & Applied Sciences')
      expect(result.code).toBe('GEAS')
    })

    it('classifies an ELECS deck with digital circuits and transistors', () => {
      const elecsCards: GenericCardInput[] = [
        {
          type: 'mcq',
          data: {
            question: 'Simplify the logic circuit function using a Karnaugh map (K-map)',
            choices: ['AB + C', 'A + B', 'A\'B', 'None'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'In an inverting operational amplifier (op-amp), calculate the closed-loop voltage gain with Rin = 10k and Rf = 100k',
            choices: ['-10', '10', '-11', '100'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'What type of flip-flop eliminates the invalid state present in an SR flip-flop?',
            choices: ['JK flip-flop', 'D flip-flop', 'T flip-flop', 'Latch'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'In the 8085 microprocessor, what register holds the 16-bit address of the next instruction to be fetched?',
            choices: ['Program Counter (PC)', 'Stack Pointer (SP)', 'Accumulator', 'Instruction Register'],
          },
        },
      ]

      const result = detectSubjectFromCards(elecsCards)
      expect(result.subject).toBe('Electronics Engineering')
      expect(result.code).toBe('ELECS')
    })

    it('classifies an EST deck with antennas and communications', () => {
      const estCards: GenericCardInput[] = [
        {
          type: 'mcq',
          data: {
            question: 'An FM broadcast transmitter has a maximum frequency deviation of 75 kHz and modulating frequency of 15 kHz. Using Carson\'s rule, find the bandwidth.',
            choices: ['180 kHz', '150 kHz', '90 kHz', '200 kHz'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'What is the characteristic impedance of a quarter-wave transformer matching a 50 ohm line to a 200 ohm load?',
            choices: ['100 ohms', '150 ohms', '75 ohms', '50 ohms'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'In fiber optics, calculate the numerical aperture given n_core = 1.48 and n_cladding = 1.45',
            choices: ['0.296', '0.145', '0.35', '0.50'],
          },
        },
        {
          type: 'mcq',
          data: {
            question: 'Which layer of the OSI model is responsible for routing and IP addressing?',
            choices: ['Network Layer', 'Transport Layer', 'Data Link Layer', 'Session Layer'],
          },
        },
      ]

      const result = detectSubjectFromCards(estCards)
      expect(result.subject).toBe('Electronics Systems & Technologies')
      expect(result.code).toBe('EST')
    })

    it('handles formula cards correctly', () => {
      const formulaCards: GenericCardInput[] = [
        {
          type: 'formula',
          data: {
            name: 'Integral of Exponential Function',
            latex: '\\int e^{ax} dx = \\frac{1}{a} e^{ax} + C',
            description: 'Standard indefinite integral for exponential function',
            variables: 'a = constant',
          },
        },
        {
          type: 'formula',
          data: {
            name: 'Laplace Transform of Sine',
            latex: '\\mathcal{L}\\{\\sin(\\omega t)\\} = \\frac{\\omega}{s^2 + \\omega^2}',
            description: 'Laplace transform table',
            variables: 's = complex frequency',
          },
        },
      ]

      const result = detectSubjectFromCards(formulaCards)
      expect(result.subject).toBe('Mathematics')
    })

    it('returns sensible default for empty cards without crashing', () => {
      const result = detectSubjectFromCards([])
      expect(result.subject).toBe('Electronics Engineering')
      expect(result.confidence).toBe(0)
    })
  })
})
